/// Individual asset target allocation weight.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct AssetWeight {
    pub symbol: String,
    pub target_weight: BasisPoints,
}

/// Portfolio target allocation target ensuring sum to 10,000 bps.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct AllocationTarget {
    pub weights: Vec<AssetWeight>,
}

impl AllocationTarget {
    pub fn new(weights: Vec<AssetWeight>) -> Result<Self, ValidationError> {
        validation::validate_weights_sum(&weights)?;
        Ok(Self { weights })
    }

    pub fn total_weight_bps(&self) -> u16 {
        self.weights.iter().map(|w| w.target_weight.0).sum()
    }

    pub fn get_weight(&self, symbol: &str) -> Option<BasisPoints> {
        self.weights
            .iter()
            .find(|w| w.symbol == symbol)
            .map(|w| w.target_weight)
    }
}

